GRADERS = ("function", "fit", "cost")
GRAVITY_M_S2 = 9.80665
RESOLVABLE = {"F7": "F7_z_ball_nut_capacity", "G10": "G10_thread_engagement", "G9": "G9_envelope"}  # computed checks


@dataclass(frozen=True)
class Case:
    """A design case: the ZXVerbinder solids, the applied substitutions and the parts they replace (source frame)."""
    case_id: str
    connectors: tuple
    design_value: object = None  # rule 1 parameter value, if the case was generated by the rule
    substitutions: tuple = ()  # applied substitution entries (config.substitutions)
    replaced: dict = field(default_factory=dict)  # part index -> measured facts, or None for a removed part
    reference: bool = False


def option_solids(cache, rule, value):
    """Apply the rule to the first occurrence and place the copy at every original placement (source frame)."""
    trimmed = trim_symmetric_x(cache.connectors[0], value, rule["protected_features"]["bolt_seat_radius_mm"])
    return tuple(trimmed.Moved(offset) for offset in occurrence_offsets(cache.connectors))


def substitution_shapes(sub, cache):
    """Declared simplified solids of a substitution: [(part index, case part name, shape, or None if removed)]."""
    facts, geometry = cache.facts, sub["geometry"]
    indices = [p["index"] for p in facts["parts"] if p["name"] == sub["part"]]
    removed = [(p["index"], None, None) for p in facts["parts"] if p["name"] in sub.get("includes", ())]
    if geometry["type"] == "motor_envelope":
        motor = facts["z_motor"]
        if motor is None or indices != [motor["index"]]:
            raise ValueError(f"{sub['id']}: no motor anchor facts for {sub['part']}")
        name = f"{sub['to'].split(',')[0]} ({sub['id']}, simplified envelope)"
        return [(motor["index"], name, motor_envelope(motor["axis_x"], motor["axis_y"], motor["flange_face_z"], geometry["body_mm"],
                                                      geometry["shaft_diameter_mm"], geometry["shaft_length_mm"]))] + removed
    anchors = {j["index"]: j for j in facts["threaded_joints"]}
    if not indices or any(i not in anchors for i in indices):
        raise ValueError(f"{sub['id']}: no head-seat anchor facts for {sub['part']}")

    def screw(joint):
        seat = list(joint["point"])
        seat.insert(joint["axis"], joint["head_seat"])
        direction = [joint["direction"] if k == joint["axis"] else 0 for k in range(3)]
        return socket_head_screw(seat, direction, geometry["shank_diameter_mm"], geometry["length_mm"],
                                 geometry["head_diameter_mm"], geometry["head_height_mm"])
    name = f"socket head cap screw M{geometry['shank_diameter_mm']:g} x {geometry['length_mm']:g} ({sub['id']}, simplified)"
    return [(i, name, screw(anchors[i])) for i in indices] + removed


def _key(shape):
    return tuple(round((a + b) / 2, 2) for a, b in zip(bounds(shape)[:3], bounds(shape)[3:]))


def assign_solids(cache, declared, shapes):
    """Measured facts per replaced part index: the given solids matched to the declared ones by box centre."""
    placed = sorted((item for item in declared if item[2] is not None), key=lambda item: _key(item[2]))
    shapes = sorted(shapes, key=_key)
    if len(shapes) != len(placed):
        raise ValueError(f"Expected {len(placed)} substituted solids, got {len(shapes)}")
    parents = {p["index"]: tuple(p["parents"]) for p in cache.facts["parts"]}
    result = {i: part_facts(i, PlacedPart(name, parents[i], shape)) for (i, name, _), shape in zip(placed, shapes)}
    return {**result, **{i: None for i, _, shape in declared if shape is None}}


def measured_parts(cache, connector_solids, replaced=None):
    """Facts of every part: ZXVerbinder slots measured from the given solids, replaced parts swapped or removed."""
    parts = [dict(p) for p in cache.facts["parts"]]
    for index, shape in zip(cache.facts["connector_indices"], connector_solids):
        parts[index] = part_facts(index, PlacedPart(CONNECTOR, tuple(parts[index]["parents"]), shape))
    for index, facts in (replaced or {}).items():
        parts[index] = facts
    return [p for p in parts if p is not None]


def connector_geometry(originals, cases, cache, config):
    """The geometry-heavy records (F1-F4, G1-G3, ball-nut pad), shared by every case with the same ZXVerbinder solids."""
    return {"function": connector_function_checks(originals, cases, cache, config),
            "fit": connector_fit_checks(originals, cases, config.rule)}


def baseline_findings(cache, config):
    """The original design's own failures and unknowns (not caused by any change)."""
    solids = sorted((b for p in cache.facts["parts"] for b in (p["solid_bounds"] or [p["bounds"]])), key=lambda b: -b[5])
    z_min = min(b[2] for b in solids)
    extremes = cache.facts["native_extremes"]["z"]
    tool = cache.facts["parts"][extremes["max"]["part"]]
    thrust, rating = lc2_drive(config, ())[0], config.z_ball_nut["static_axial_rating_N"]["value"]
    factor = config.requirements["limits"]["safety_factor_yield_LC2"]["minimum"]
    parts = {p["index"]: p for p in cache.facts["parts"]}
    gaps = {}
    for j in cache.facts["threaded_joints"]:
        b = parts[j["index"]]["bounds"]
        gaps[j["joint"]] = (j["thread_near"] - (b[j["axis"] + 3] if j["direction"] > 0 else b[j["axis"]])) * j["direction"]
    return [
        {"check": "F7", "finding": f"Z ball nut static rating {rating:g} N / LC2 thrust {thrust:.0f} N = "
                                   f"{rating / thrust:.2f} {'<' if rating / thrust < factor else '>='} {factor} (nut identity to verify: BOM names Dold "
                                   "Mechatronic, rating from Isel catalog)."},
        {"check": "G10", "finding": "Screws engage 0 mm: " + "; ".join(f"{k} ends {g:.1f} mm short of its thread"
                                                                        for k, g in gaps.items())
                                    + f" (required {config.thread_engagement_ratio:g} x d)."},
        {"check": "F5/F6", "finding": "Whole-assembly peak stress under LC1 and LC2 is not modelled."},
        g9_finding(cache, config, solids[0][5] - z_min, solids[1][5] - z_min, tool["name"], extremes["max"]["solid"]),
        {"check": "G6", "finding": f"Z travel {config.z_travel['travel_mm']:.2f} mm was measured once by the old repo's "
                                   f"static sweep (2 mm steps) and is carried; it is not recomputed in this repo. Rail "
                                   f"coverage {cache.facts['rail_coverage']['coverage_mm']:.1f} mm."}]


def g9_finding(cache, config, span, span_without_tool, tool_name, tool_number):
    registration = register(cache.facts, config.requirements)
    tool = tool_report(cache.facts, registration)
    text = (f"Native Z span {span:.3f} mm includes {tool_name} solid {tool_number} (the tool); {span_without_tool:.3f} mm "
            "without it.")
    if tool:
        points = config.requirements["reference_points"]
        text += (f" Registered to the YAML frame: tool tip z {tool['tool_tip_z']:.1f} (YAML "
                 f"{points['tool_tip']['z_mm']['value']}), spindle body ends at z {tool['spindle_nose_z']:.1f} (YAML nose "
                 f"{points['spindle_nose_z_mm']['value']}): the CAD tool sticks out {tool['stick_out_mm']:.1f} mm, the YAML "
                 f"assumes {points['tool_stick_out_mm']['value']} mm (YAML values used; G9 excludes the tool).")
    return {"check": "G9", "finding": text}


def highest_speed(points, target):
    """Highest speed (rpm) at which the linearly interpolated pull-out curve is >= target, or None."""
    best = None
    for (r0, t0), (r1, t1) in zip(points, points[1:]):
        if t1 >= target:
            best = r1
        elif t0 >= target:
            best = r0 + (t0 - target) / (t0 - t1) * (r1 - r0)
    return best


def speed_records(params, required, drive_inputs, source):
    """INFO: highest Z speed at which the pull-out torque is >= speed_safety_factor x the torque each force needs."""
    curve, factor = params["pull_out_torque"], params.get("speed_safety_factor", 1)
    pitch, eta = drive_inputs["screw_pitch"]["value"], drive_inputs["screw_efficiency"]["value"]
    records = {}
    for name, force in (("z_speed_cutting", required), ("z_speed_rapid", required - params["plunge_force_N"])):
        torque = force * pitch / 1000 / (2 * pi * eta) * 100  # N cm
        rpm = highest_speed(curve["points_rpm_Ncm"], factor * torque)
        records[name] = value_record(
            "speed = pitch * highest rpm with pull_out_torque(rpm) >= factor * required_torque (linear interpolation); "
            "required_torque = force * pitch / (2*pi*screw_efficiency)",
            {"force": measured(force, "N"), "screw_pitch": measured(pitch, "mm"), "screw_efficiency": measured(eta, "1"),
             "required_torque": measured(torque, "N cm"), "factor": measured(factor, "1"),
             "target_pull_out_torque": measured(factor * torque, "N cm"),
             **({"rpm": measured(rpm, "rpm")} if rpm is not None else {})}, None if rpm is None else rpm * pitch, "mm/min",
            reason=f"{source}: pull-out curve {curve['conditions']} ({curve['source']}). The YAML gives no Z speed "
                   "requirement; this is information, not a grader. Our driver and supply voltage are not known.")
    return records


def drive_information(case_parts, cache, config, substitutions):
    """INFO: Z drive force capacity of a substituted motor against moving the Z head (not a grader)."""
    checks = [s for s in substitutions if "drive_check" in s]
    if not checks:
        return {}
    req = config.requirements
    params = {**checks[0]["drive_check"], "plunge_force_N": load_case(req, "LC1")["force_N"]["value"]}  # plunge = LC1 force
    density = {STEP_NAME_ALIASES.get(p["part_id"], p["part_id"]): material_properties(req, p["material"])["density_g_cm3"]["value"]
               for p in req["made_parts"]["parts"]}
    members = [p for p in case_parts if p["index"] in set(cache.facts["z_moving_set"]["indices"]) and p["volume_mm3"]]
    mass = sum(p["volume_mm3"] * 1e-6 * density.get(p["name"], params["bought_part_density_g_cm3"]) for p in members)
    capacity, inputs, _ = lc2_drive(config, substitutions)
    required = mass * (GRAVITY_M_S2 + params["acceleration_m_s2"]) + params["plunge_force_N"]
    speeds = speed_records(params, required, inputs, checks[0]["id"]) if "pull_out_torque" in params else {}
    return {**speeds, "z_drive_force_capacity": value_record(
        f"margin = capacity / required; capacity = {LC2_FORMULA}; "
        "required = moving_mass * (g + acceleration) + plunge_force; plunge_force = LC1 force_N",
        {**inputs, "capacity": measured(capacity, "N"), "moving_mass": measured(mass, "kg"), "g": measured(GRAVITY_M_S2, "m/s^2"),
         "acceleration": measured(params["acceleration_m_s2"], "m/s^2"), "plunge_force": measured(params["plunge_force_N"], "N"),
         "required": measured(required, "N"), "moving_parts_with_volume": measured(len(members), "count")},
        capacity / required, "1", reason=f"{checks[0]['id']}: {params['source']}. Holding torque; the torque falls with speed.")}


def evaluate_case(case, cache, config, geometry=None):
    """Grade a case against the cached original assembly. geometry: precomputed connector_geometry() (optional)."""
    cases = tuple(sorted(case.connectors, key=lambda s: bounds(s)[2]))
    originals = cache.connectors
    if len(cases) != len(originals):
        raise ValueError(f"{case.case_id}: expected {len(originals)} {CONNECTOR} solids, got {len(cases)}")
    parents = {p["index"]: tuple(p["parents"]) for p in cache.facts["parts"]}
    expected = {sub["id"]: {i: None if shape is None else part_facts(i, PlacedPart(name, parents[i], shape))
                            for i, name, shape in substitution_shapes(sub, cache)} for sub in case.substitutions}
    original_parts, case_parts = measured_parts(cache, originals), measured_parts(cache, cases, case.replaced)
    changes = [(config.rule["rule_id"], config.rule["unchanged_proofs"])] + [(s["id"], s["unchanged_proofs"]) for s in case.substitutions]
    geometry = geometry or connector_geometry(originals, cases, cache, config)
    checks = {"function": function_checks(originals, cases, cache, config, changes, case.substitutions, geometry["function"]),
              "fit": fit_checks(originals, cases, original_parts, case_parts, cache, config, changes, case.substitutions,
                                expected, geometry["fit"]),
              "cost": cost_checks(original_parts, case_parts, CONNECTOR, config, case.substitutions)}
    # Proofs name checks by their short id (G0, G3, ...).
    statuses = {key.split("_", 1)[0]: record["status"] for grader in checks.values() for key, record in grader.items()}
    named = {c for grader in checks.values() for record in grader.values() for c in record.get("proof", {}).get("checks", ())}
    if named - statuses.keys():
        raise ValueError(f"Proof names unknown checks: {sorted(named - statuses.keys())}")
    for record in (r for grader in checks.values() for r in grader.values() if r["status"] == UNCHANGED):
        record["proof"]["holds"] = proof_holds(record["proof"], statuses)
    report = {"case_id": case.case_id, "changed_parts": [CONNECTOR] + [s["part"] for s in case.substitutions],
              "design_value": case.design_value, "substitutions": [s["id"] for s in case.substitutions]}
    for grader in GRADERS:
        report[grader] = {"summary": grader_summary(grader, checks[grader], statuses), "checks": checks[grader]}
    passed = all(report[g]["summary"]["status"] == PASS for g in GRADERS)
    report["verdict"] = "REFERENCE" if case.reference else ("ACCEPT" if passed else "REJECT")
    findings = baseline_findings(cache, config)
    resolved = {short for short, key in RESOLVABLE.items()
                if next(g["checks"][key] for g in (report["function"], report["fit"]) if key in g["checks"])["status"] == PASS}
    # One entry per check: a failing record joins the original finding of the same check (F7, G10, F5/F6, ...).
    failed = [key for g in GRADERS for key in report[g]["summary"]["failed_checks"]]
    open_findings = [f for f in findings if f["check"] not in resolved]
    matched = {f["check"]: [k for k in failed if k.split("_", 1)[0] in f["check"].split("/")] for f in open_findings}
    remaining = ([{"check": key, "status": "FAIL", "finding": "FAIL (or UNCHANGED whose proof does not hold)"}
                  for key in failed if not any(key in m for m in matched.values())]
                 + [{**f, "status": "FAIL" if matched[f["check"]] else "open", "failed_records": matched[f["check"]]}
                    for f in open_findings])
    report["compliance"] = "full" if not remaining else remaining
    report["information"] = drive_information(case_parts, cache, config, case.substitutions)
    registration = register(cache.facts, config.requirements)
    report["datum"] = {**registration, "tool": tool_report(cache.facts, registration)}
    report["baseline_findings"] = findings
    validate_report(report)
    return report


def remaining_findings(report):
    """Original findings the case leaves open (the selection tie-break)."""
    return 0 if report["compliance"] == "full" else sum(f["check"] in ("F7", "G10", "F5/F6", "G9", "G6") for f in report["compliance"])


def blocking_checks(reports_fail_ids):
    """Checks that fail in every graded option (why no option is ACCEPT)."""
    sets = [set(ids.split()) for ids in reports_fail_ids]
    return sorted(set.intersection(*sets)) if sets else []


def option_row(report):
    """The options.csv / bench summary of one report."""
    c3 = report["cost"]["checks"]["C3_cost_delta"]
    value = lambda grader, key: report[grader]["checks"][key]["result"]["value"]  # noqa: E731
    fails = [k for g in GRADERS for k in report[g]["summary"]["failed_checks"]]
    return {"delta_made_eur": c3["inputs"].get("made_parts_delta", {}).get("value"),
            "delta_bought_eur": c3["inputs"]["bought_parts_delta"]["value"], "delta_total_eur": c3["result"]["value"],
            "f4_bound": value("function", "F4_deflection_ratio_bound"), "f7_safety_factor": value("function", "F7_z_ball_nut_capacity"),
            "f7_status": report["function"]["checks"]["F7_z_ball_nut_capacity"]["status"],
            "g10_engagement_d": value("fit", "G10_thread_engagement"), "g10_status": report["fit"]["checks"]["G10_thread_engagement"]["status"],
            "verdict": report["verdict"], "remaining_findings": remaining_findings(report),
            "compliance": "full" if report["compliance"] == "full" else "; ".join(sorted({f["check"] for f in report["compliance"]})),
            "fail_ids": " ".join(fails), "function": report["function"]["summary"]["status"],
            "fit": report["fit"]["summary"]["status"], "cost": report["cost"]["summary"]["status"]}
